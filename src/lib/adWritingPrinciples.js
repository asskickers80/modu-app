// 연차 라벨('3개월'·'2년'·'5년 이상')로 톤 분기 — 1년 내외 = 새것 톤
export function isFresh(ageLabel) {
  if (!ageLabel) return false
  if (/개월/.test(ageLabel)) return true
  const y = parseInt(String(ageLabel), 10)
  return Number.isFinite(y) && y <= 1
}
